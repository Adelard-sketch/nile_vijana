<?php
declare(strict_types=1);

namespace App\Services;

use App\Core\HttpException;

/**
 * File storage.
 *  - Audio, WAV and stems are PRIVATE: saved under storage/private (not web-accessible)
 *    and only served through the API (streams, previews, signed download links).
 *  - Images are PUBLIC: saved under public/uploads and served directly by the web server.
 * File types are checked from the file's content (finfo), not from the name the user sent.
 */
final class Storage
{
    public const AUDIO = [
        'audio/mpeg' => 'mp3', 'audio/mp3' => 'mp3',
        'audio/wav' => 'wav', 'audio/x-wav' => 'wav', 'audio/wave' => 'wav', 'audio/vnd.wave' => 'wav',
        'audio/x-m4a' => 'm4a', 'audio/mp4' => 'm4a', 'audio/aac' => 'aac',
        'audio/ogg' => 'ogg', 'audio/flac' => 'flac', 'audio/x-flac' => 'flac',
    ];
    public const MP3 = ['audio/mpeg' => 'mp3', 'audio/mp3' => 'mp3'];
    public const WAV = ['audio/wav' => 'wav', 'audio/x-wav' => 'wav', 'audio/wave' => 'wav', 'audio/vnd.wave' => 'wav'];
    public const ZIP = ['application/zip' => 'zip', 'application/x-zip-compressed' => 'zip'];
    public const IMAGE = ['image/jpeg' => 'jpg', 'image/png' => 'png', 'image/webp' => 'webp'];

    public const MIME_BY_EXT = [
        'mp3' => 'audio/mpeg', 'wav' => 'audio/wav', 'm4a' => 'audio/mp4', 'aac' => 'audio/aac',
        'ogg' => 'audio/ogg', 'flac' => 'audio/flac', 'zip' => 'application/zip', 'pdf' => 'application/pdf',
    ];

    /** Save an uploaded file privately. Returns a path relative to storage/private. */
    public static function storePrivate(array $file, string $folder, array $allowed, int $maxMb, string $field): string
    {
        $ext = self::check($file, $allowed, $maxMb, $field);
        $relative = $folder . '/' . date('Y/m') . '/' . bin2hex(random_bytes(12)) . '.' . $ext;
        self::move($file['tmp_name'], self::privatePath($relative));
        return $relative;
    }

    /** Save an uploaded image publicly. Returns a path relative to public/uploads. */
    public static function storeImage(array $file, string $folder, string $field): string
    {
        $ext = self::check($file, self::IMAGE, (int) config('uploads.max_image_mb', 5), $field);
        $relative = $folder . '/' . date('Y/m') . '/' . bin2hex(random_bytes(12)) . '.' . $ext;
        self::move($file['tmp_name'], BASE_PATH . '/public/uploads/' . $relative);
        return $relative;
    }

    public static function privatePath(string $relative): string
    {
        // Block "../" tricks: relative paths are always generated by us, but be safe.
        if (str_contains($relative, '..')) {
            throw new \RuntimeException('Invalid storage path');
        }
        return BASE_PATH . '/storage/private/' . $relative;
    }

    /** A new empty private path for files we generate (FFmpeg output). */
    public static function newPrivatePath(string $folder, string $ext): string
    {
        return $folder . '/' . date('Y/m') . '/' . bin2hex(random_bytes(12)) . '.' . $ext;
    }

    public static function mimeFor(string $path): string
    {
        return self::MIME_BY_EXT[strtolower(pathinfo($path, PATHINFO_EXTENSION))] ?? 'application/octet-stream';
    }

    public static function deletePrivate(?string $relative): void
    {
        if ($relative && is_file(self::privatePath($relative))) {
            @unlink(self::privatePath($relative));
        }
    }

    private static function check(array $file, array $allowed, int $maxMb, string $field): string
    {
        $err = $file['error'] ?? UPLOAD_ERR_NO_FILE;
        if ($err === UPLOAD_ERR_INI_SIZE || $err === UPLOAD_ERR_FORM_SIZE) {
            throw HttpException::invalid('File too large', [$field => 'The server upload limit was exceeded (check upload_max_filesize in php.ini)']);
        }
        if ($err !== UPLOAD_ERR_OK || !is_uploaded_file($file['tmp_name'])) {
            throw HttpException::invalid('Upload failed', [$field => 'The file did not upload correctly (error ' . $err . ')']);
        }
        if ($file['size'] > $maxMb * 1024 * 1024) {
            throw HttpException::invalid('File too large', [$field => "Maximum size is {$maxMb} MB"]);
        }

        $mime = (new \finfo(FILEINFO_MIME_TYPE))->file($file['tmp_name']) ?: 'application/octet-stream';
        if (isset($allowed[$mime])) {
            return $allowed[$mime];
        }
        // Some MP3s without ID3 tags are detected as generic binary; accept them by extension.
        $nameExt = strtolower(pathinfo((string) ($file['name'] ?? ''), PATHINFO_EXTENSION));
        if ($mime === 'application/octet-stream' && in_array($nameExt, ['mp3', 'wav', 'zip'], true) && in_array($nameExt, $allowed, true)) {
            return $nameExt;
        }
        throw HttpException::invalid('Wrong file type', [
            $field => 'Allowed types: ' . implode(', ', array_unique(array_values($allowed))) . " (got $mime)",
        ]);
    }

    private static function move(string $tmp, string $dest): void
    {
        $dir = dirname($dest);
        if (!is_dir($dir) && !mkdir($dir, 0775, true) && !is_dir($dir)) {
            throw new \RuntimeException("Cannot create folder $dir");
        }
        if (!move_uploaded_file($tmp, $dest)) {
            throw new \RuntimeException('Could not save the uploaded file');
        }
    }
}
